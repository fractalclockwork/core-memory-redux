def emit_ccs_sense_sch(out_dir: Path) -> Path:
    key = "ccs_sense"
    body, suuid = _sheet_base(
        key,
        "pcb_ccs_sense — CCS×3 + sense/fold + Pico + bus host",
        8,
        [_lib_r()],
    )
    items: list = [
        _text(f"{key}/banner", BANNER_BOARD.format(board="ccs"), 10, 8),
        _text(
            f"{key}/tune",
            "Tune: RTRIM_X/Y/INH (3296W), VDRIVE, JP_INH_POL — design_choices",
            10,
            13,
        ),
        _text(f"{key}/fold", "YA66 ≡ YB65 ≡ SENSE_FOLD (local fold)", 10, 18),
    ]

    # Three CCS trimpot stubs (pin1 wiper label, pin2 AGND).
    tx, ty = 180.0, 30.0
    for ref in CCS_TRIM_REFS:
        items.append(_place_r(f"{key}/{ref}", ref, "3296W", tx, ty, suuid))
        items.append(_global_label(f"{ref}_WIPER", tx, ty - 3.81, 90))
        items.append(_global_label("AGND", tx, ty + 3.81, 270))
        tx += 25.0

    items.append(_place_r(f"{key}/Rfold", "Rfold", "10k", 180, 70, suuid))
    items.append(_global_label("SENSE_FOLD", 180, 70 - 3.81, 90))
    items.append(_global_label("AGND", 180, 70 + 3.81, 270))

    # Connector pin stubs (root sheet → global labels, not hierarchical).
    _connector_ports(items, suuid, "sense", PLANE_SENSE_PINS, 20.0, 30.0)
    _connector_ports(items, suuid, "bus", BUS_PINS, 20.0, 55.0)
    _connector_ports(items, suuid, "pico", PICO_PINS, 70.0, 30.0)

    # CCS return sense resistors: CCS_* ↔ AGND (1 Ω).
    for name, y in (("CCS_X", 100.0), ("CCS_Y", 110.0), ("CCS_INH", 120.0)):
        items.append(_place_r(f"{key}/{name}", f"R_{name}", "1", 210.0, y, suuid))
        items.append(_global_label(name, 210.0, y - 3.81, 90))
        items.append(_global_label("AGND", 210.0, y + 3.81, 270))

    body.extend(items)
    body.append(["sheet_instances", ["path", "/", ["page", "1"]]])
    path = out_dir / f"{key}.kicad_sch"
    write_sexpr(path, body)
    return path


def emit_axis_octal_sch(out_dir: Path, group: int = 0) -> Path:
    fabric = build_fabric(64)
    tile = next(t for t in fabric.tiles if t.axis == "X" and t.group == group)

    key = "axis_octal"
    body, suuid = _sheet_base(
        key,
        f"pcb_axis_octal — decode+DMOS+SS14 group g={group} (X/Y identical PCB)",
        8,
        [_lib_diode(), _lib_r()],
    )
    items: list = [
        _text(f"{key}/banner", BANNER_BOARD.format(board="axis"), 10, 8),
        _text(
            f"{key}/id",
            "JP_AXIS=X|Y  JP_G[2:0]=group  bring-up: g=0",
            10,
            13,
        ),
        _text(
            f"{key}/pins",
            f"REQ-HIER-OCTAL steer pins={AXIS_STEER_PIN_COUNT} lines={list(tile.lines)}",
            10,
            18,
        ),
        _text(
            f"{key}/mpn",
            "Decode 74AHC138+74AHC238; DMOS TBD62783/TBD62083; steer SS14",
            10,
            23,
        ),
    ]

    steer_pins = axis_steer_pins(group)
    assert len(steer_pins) == AXIS_STEER_PIN_COUNT
    _connector_ports(items, suuid, "steer", list(steer_pins), 20.0, 35.0)
    _connector_ports(items, suuid, "bus", BUS_PINS, 100.0, 35.0)
    _connector_ports(items, suuid, "plane", PLANE_AB_PINS, 180.0, 35.0)

    # SS14 diodes for this group's diode law (from fabric tile).
    dx, dy = 260.0, 35.0
    for i, edge in enumerate(tile.diodes):
        ref = f"D{group}_{i}"
        items.append(_place_diode(f"{key}/{ref}", ref, dx, dy, suuid))
        items.append(_global_label(edge.anode, dx + 5.08, dy, 0))
        items.append(_global_label(edge.cathode, dx - 5.08, dy, 180))
        items.append(_wire(f"{key}/{ref}/a", dx + 3.81, dy, dx + 5.08, dy))
        items.append(_wire(f"{key}/{ref}/k", dx - 3.81, dy, dx - 5.08, dy))
        dy += 7.62
        if dy > 180:
            dy = 35.0
            dx += 35.0

    # Fail-safe pull resistors on enables.
    items.append(_place_r(f"{key}/Rpu_fwd", "Rpu_FWD", "10k", 100, 150, suuid))
    items.append(_global_label("FWD_EN_n", 100, 150 - 3.81, 90))
    items.append(_global_label("+3V3", 100, 150 + 3.81, 270))
    items.append(_place_r(f"{key}/Rpu_rev", "Rpu_REV", "10k", 120, 150, suuid))
    items.append(_global_label("REV_EN_n", 120, 150 - 3.81, 90))
    items.append(_global_label("+3V3", 120, 150 + 3.81, 270))
    items.append(_place_r(f"{key}/Rpd_dec", "Rpd_DEC", "10k", 140, 150, suuid))
    items.append(_global_label("DEC_EN", 140, 150 - 3.81, 90))
    items.append(_global_label("AGND", 140, 150 + 3.81, 270))

    body.extend(items)
    body.append(["sheet_instances", ["path", "/", ["page", "1"]]])
    path = out_dir / f"{key}.kicad_sch"
    write_sexpr(path, body)
    return path


