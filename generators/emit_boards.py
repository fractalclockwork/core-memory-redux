def _pin_header_fp(
    ref: str,
    value: str,
    net_names: tuple[str, ...] | list[str],
    x: float,
    y: float,
    *,
    pitch: float = 2.54,
) -> list:
    """Inline 1×N vertical pin header footprint (no external lib dependency)."""
    pads = []
    nets = []
    for i, net in enumerate(net_names):
        pad_n = i + 1
        net_id = i + 1
        nets.append(["net", net_id, net])
        py = y + i * pitch
        pads.append(
            [
                "pad",
                str(pad_n),
                "thru_hole",
                "circle",
                ["at", 0, i * pitch],
                ["size", 1.7, 1.7],
                ["drill", 1.0],
                ["layers", "*.Cu", "*.Mask"],
                ["net", net_id, net],
                ["pintype", "passive"],
                ["uuid", det_uuid(f"pad/{ref}/{pad_n}")],
            ]
        )
    n = len(net_names)
    height = max(pitch, (n - 1) * pitch) + 2.0
    fp = [
        "footprint",
        f"Connector_PinHeader_2.54mm:PinHeader_1x{n}_P2.54mm_Vertical",
        ["layer", "F.Cu"],
        ["uuid", det_uuid(f"fp/{ref}")],
        ["at", x, y],
        ["descr", f"Pin header {n}x1"],
        ["tags", "connector"],
        ["property", "Reference", ref, ["at", 0, -2.5, 0], ["layer", "F.SilkS"], ["uuid", det_uuid(f"fp/{ref}/ref")]],
        ["property", "Value", value, ["at", 0, height, 0], ["layer", "F.Fab"], ["uuid", det_uuid(f"fp/{ref}/val")]],
        ["property", "Footprint", "", ["at", 0, 0, 0], ["layer", "F.Fab"], ["hide", True], ["uuid", det_uuid(f"fp/{ref}/fp")]],
        ["property", "Datasheet", "", ["at", 0, 0, 0], ["layer", "F.Fab"], ["hide", True], ["uuid", det_uuid(f"fp/{ref}/ds")]],
        ["property", "Description", "", ["at", 0, 0, 0], ["layer", "F.Fab"], ["hide", True], ["uuid", det_uuid(f"fp/{ref}/desc")]],
        ["attr", "through_hole"],
        [
            "fp_line",
            ["start", -1.5, -1.5],
            ["end", 1.5, -1.5],
            ["stroke", ["width", 0.12], ["type", "solid"]],
            ["layer", "F.SilkS"],
            ["uuid", det_uuid(f"fp/{ref}/silk1")],
        ],
        [
            "fp_rect",
            ["start", -1.8, -1.8],
            ["end", 1.8, (n - 1) * pitch + 1.8],
            ["stroke", ["width", 0.05], ["type", "solid"]],
            ["fill", "none"],
            ["layer", "F.CrtYd"],
            ["uuid", det_uuid(f"fp/{ref}/crtyd")],
        ],
        *pads,
    ]
    return fp, nets


def _emit_pcb(
    out_dir: Path,
    name: str,
    width_mm: float,
    height_mm: float,
    connectors: list[tuple[str, str, tuple[str, ...] | list[str], float, float]],
) -> Path:
    """Fab-oriented PCB: outline + connectors. Each net on at most one pad (no autoroute)."""
    all_nets: dict[str, int] = {}
    net_list: list = [["net", 0, ""]]
    footprints: list = []
    seen: set[str] = set()

    next_id = 1
    pitch = 2.54
    for ref, value, pins, x, y in connectors:
        local_nets = []
        for p in pins:
            if p in seen:
                raise ValueError(
                    f"PCB {name}: net {p!r} repeated on {ref}; "
                    "keep one pad per net for DRC-clean connector boards"
                )
            seen.add(p)
            if p not in all_nets:
                all_nets[p] = next_id
                net_list.append(["net", next_id, p])
                next_id += 1
            local_nets.append(p)
        fp, _ = _pin_header_fp(ref, value, local_nets, x, y, pitch=pitch)
        for node in fp:
            if isinstance(node, list) and node and node[0] == "pad":
                for i, sub in enumerate(node):
                    if isinstance(sub, list) and sub and sub[0] == "net":
                        nname = sub[2]
                        node[i] = ["net", all_nets[nname], nname]
        footprints.append(fp)

    body: list = [
        "kicad_pcb",
        ["version", KICAD_PCB_VERSION],
        ["generator", "core-memory-redux"],
        ["generator_version", "10.0"],
        ["general", ["thickness", 1.6], ["legacy_teardrops", False]],
        ["paper", "A4"],
        _pcb_layers_2(),
        [
            "setup",
            ["pad_to_mask_clearance", 0],
            [
                "pcbplotparams",
                ["layerselection", "0x00010fc_ffffffff"],
                ["plot_on_all_layers_selection", "0x0000000_00000000"],
                ["disableapertmacros", False],
                ["usegerberextensions", False],
                ["usegerberattributes", True],
                ["usegerberadvancedattributes", True],
                ["creategerberjobfile", True],
                ["dashed_line_dash_ratio", 12],
                ["dashed_line_gap_ratio", 3],
                ["svgprecision", 4],
                ["plotframeref", False],
                ["mode", 1],
                ["useauxorigin", False],
                ["hpglpennumber", 1],
                ["hpglpenspeed", 20],
                ["hpglpendiameter", 15],
                ["pdf_front_fp_property_popups", True],
                ["pdf_back_fp_property_popups", True],
                ["dxfpolygonmode", True],
                ["dxfimperialunits", True],
                ["dxfusepcbnewfont", True],
                ["psnegative", False],
                ["psa4output", False],
                ["plotreference", True],
                ["plotvalue", True],
                ["plotfptext", True],
                ["plotinvisibletext", False],
                ["sketchpadsonfab", False],
                ["subtractmaskfromsilk", False],
                ["outputformat", 1],
                ["mirror", False],
                ["drillshape", 1],
                ["scaleselection", 1],
                ["outputdirectory", ""],
            ],
        ],
        *net_list,
        [
            "gr_rect",
            ["start", 0, 0],
            ["end", width_mm, height_mm],
            ["stroke", ["width", 0.1], ["type", "default"]],
            ["fill", "none"],
            ["layer", "Edge.Cuts"],
            ["uuid", det_uuid(f"edge/{name}")],
        ],
        [
            "gr_text",
            name,
            ["at", width_mm / 2, 5],
            ["layer", "F.SilkS"],
            ["uuid", det_uuid(f"silk/{name}")],
            ["effects", ["font", ["size", 2, 2], ["thickness", 0.3]]],
        ],
        *footprints,
    ]
    path = out_dir / f"{name}.kicad_pcb"
    write_sexpr(path, body)
    return path


