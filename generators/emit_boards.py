def _emit_pro(out_dir: Path, name: str, root_sheet: str) -> None:
    """Emit KiCad 10 JSON project; stem must match root .kicad_sch / .kicad_pcb."""
    root_uuid = det_uuid(f"sheet/{root_sheet}")
    pro = {
        "board": {
            "design_settings": {
                "defaults": {},
                "diff_pair_dimensions": [],
                "drc_exclusions": [],
                "rules": {},
                "track_widths": [],
                "via_dimensions": [],
            }
        },
        "boards": [],
        "libraries": {"pinned_footprint_libs": [], "pinned_symbol_libs": []},
        "meta": {"filename": f"{name}.kicad_pro", "version": 3},
        "net_settings": {"classes": [], "meta": {"version": 0}},
        "pcbnew": {"page_layout_descr_file": ""},
        "schematic": {
            "meta": {"version": 1},
            "page_layout_descr_file": "",
            "plot_directory": "",
        },
        "sheets": [[root_uuid, "Root"]],
        "text_variables": {},
    }
    (out_dir / f"{name}.kicad_pro").write_text(
        json.dumps(pro, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )


def _root_port(name: str, x: float, y: float, sheet_uuid: str) -> list[list]:
    """Global-label connector stub (two stubs — avoids isolated_pin_label)."""
    x, y = snap(x), snap(y)
    rx = snap(x + 12.7)
    rx2 = snap(x + 15.24)
    ref = "TP_" + "".join(c if c.isalnum() else "_" for c in f"{name}_{x:g}_{y:g}")[:20]
    return [
        _global_label(name, x, y, 0),
        _wire(f"port/{name}@{x},{y}", x, y, rx, y),
        _place_stub(f"portStub/{name}@{x},{y}", ref, rx, y, sheet_uuid),
        _wire(f"porth/{name}@{x},{y}", rx, y, rx2, y),
        _place_stub(f"portStub2/{name}@{x},{y}", ref + "b", rx2, y, sheet_uuid),
    ]


def _connector_ports(
    items: list,
    suuid: str,
    prefix: str,
    pins: tuple[str, ...] | list[str],
    x0: float,
    y0: float,
) -> None:
    del prefix  # reserved for future silkscreen grouping
    y = y0
    x = x0
    for pin in pins:
        items.extend(_root_port(pin, x, y, suuid))
        y += 2.54
        if y > 180:
            y = y0
            x += 40.0


