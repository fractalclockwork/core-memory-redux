    items.extend(_global_label_terminated("REV_EN_n", 280.0, 150.0, suuid, 0))
    items.extend(_global_label_terminated("DEC_EN", 300.0, 150.0, suuid, 0))

    # SS14 steer array (CMR diode + labels — topology SSOT)
    dx, dy = 260.0, 165.0
    for i, edge in enumerate(tile.diodes):
        ref = f"D{group}_{i}"
        items.append(_place_diode(f"{key}/{ref}", ref, dx, dy, suuid))
        items.extend(_global_label_terminated(edge.anode, dx + 5.08, dy, suuid, 0))
        items.extend(_global_label_terminated(edge.cathode, dx - 5.08, dy, suuid, 180))
        items.append(_wire(f"{key}/{ref}/a", dx + 3.81, dy, dx + 5.08, dy))
        items.append(_wire(f"{key}/{ref}/k", dx - 3.81, dy, dx - 5.08, dy))
        dy += 7.62
        if dy > 260:
            dy = 165.0
            dx += 35.0

    lib_node = next(n for n in body if isinstance(n, list) and n and n[0] == "lib_symbols")
    for sym in lib_cache.values():
        lib_node.append(sym)

    body.extend(items)
    body.append(["sheet_instances", ["path", "/", ["page", "1"]]])
    path = out_dir / f"{key}.kicad_sch"
    write_sexpr(path, body)
    return path


