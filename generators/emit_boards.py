    place_part_nc(PART_74AHC138, "U_HS_REV", 300.0, 40.0, suuid, lib_cache, items)
    place_part_nc(PART_74AHC238, "U_LS_FWD", 260.0, 90.0, suuid, lib_cache, items)
    place_part_nc(PART_74AHC238, "U_LS_REV", 300.0, 90.0, suuid, lib_cache, items)
    place_part_nc(PART_TBD62783, "U_DMOS_HS_FWD", 340.0, 40.0, suuid, lib_cache, items)
    place_part_nc(PART_TBD62783, "U_DMOS_HS_REV", 380.0, 40.0, suuid, lib_cache, items)
    place_part_nc(PART_TBD62083, "U_DMOS_LS_FWD", 340.0, 90.0, suuid, lib_cache, items)
    place_part_nc(PART_TBD62083, "U_DMOS_LS_REV", 380.0, 90.0, suuid, lib_cache, items)

    # Fail-safe resistors (also place stock Device:R for footprint on PCB)
    place_part_nc(PART_R10K, "Rpu_FWD", 260.0, 140.0, suuid, lib_cache, items)
    place_part_nc(PART_R10K, "Rpu_REV", 280.0, 140.0, suuid, lib_cache, items)
    place_part_nc(PART_R10K, "Rpd_DEC", 300.0, 140.0, suuid, lib_cache, items)
