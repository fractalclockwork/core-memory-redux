def _clean_generated(out_dir: Path) -> None:
    if not out_dir.exists():
        return
    for pattern in ("*.kicad_sch", "*.kicad_pro", "*.kicad_pcb", "*_manifest.json", "README.md"):
        for p in out_dir.glob(pattern):
            p.unlink()


def emit_board(board: str, kicad_root: Path | None = None) -> Path:
    """board: 'ccs' | 'axis' | 'all'."""
    root = kicad_root or KICAD_ROOT
    board = board.lower()
    if board == "all":
        paths = [emit_board("ccs", root), emit_board("axis", root)]
        return paths[-1]

    if board in ("ccs", "ccs_sense", "pcb_ccs_sense"):
        name = "pcb_ccs_sense"
        out = root / name
        _clean_generated(out)
        out.mkdir(parents=True, exist_ok=True)
        sch = emit_ccs_sense_sch(out)
        pcb = emit_ccs_sense_pcb(out)
        _emit_pro(out, name, name)
        manifest = {
            "board": name,
            "root_sch": sch.name,
            "pcb": pcb.name,
            "bus_pins": list(BUS_PINS),
            "sense_pins": list(PLANE_SENSE_PINS),
            "sense_pcb_pins": list(PLANE_SENSE_PCB_PINS),
            "pico_pins": list(PICO_PINS),
            "pico_pcb_pins": list(PICO_PCB_PINS),
            "ccs_trims": list(CCS_TRIM_REFS),
            "sense_nets": sorted(SENSE_NETS),
            "stackup": "2-layer fab prototype; 4-layer preferred",
            "role": "CCS + sense + power/bus distribution",
        }
        (out / "board_manifest.json").write_text(
            json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8"
        )
        (out / "README.md").write_text(
            f"# {name} (GENERATED)\n\n"
            f"{BANNER_BOARD.format(board='ccs')}\n\n"
            f"- Schematic: `{sch.name}`\n"
            f"- PCB: `{pcb.name}`\n"
            f"- ICD: `docs/board_icd.md`\n",
            encoding="utf-8",
        )
        return out

    if board in ("axis", "axis_octal", "pcb_axis_octal"):
        name = "pcb_axis_octal"
        out = root / name
        _clean_generated(out)
        out.mkdir(parents=True, exist_ok=True)
        sch = emit_axis_octal_sch(out, group=0)
        pcb = emit_axis_octal_pcb(out)
        _emit_pro(out, name, name)
        steer = axis_steer_pins(0)
        manifest = {
            "board": name,
            "root_sch": sch.name,
            "pcb": pcb.name,
            "bus_pins": list(BUS_PINS),
            "plane_ab_pins": list(PLANE_AB_PINS),
            "steer_pin_count": len(steer),
            "steer_pins": list(steer),
            "sense_nets_forbidden": sorted(SENSE_NETS),
            "group_bringup": 0,
            "stackup": "2-layer fab prototype; 4-layer preferred",
        }
        (out / "board_manifest.json").write_text(
            json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8"
        )
        (out / "README.md").write_text(
            f"# {name} (GENERATED)\n\n"
            f"{BANNER_BOARD.format(board='axis')}\n\n"
            f"- Schematic: `{sch.name}`\n"
            f"- PCB: `{pcb.name}`\n"
            f"- Identical PCB for X and Y; strap JP_AXIS / JP_G\n"
            f"- ICD: `docs/board_icd.md`\n",
            encoding="utf-8",
        )
        return out

    raise ValueError(f"unknown board {board!r}; use ccs|axis|all")
