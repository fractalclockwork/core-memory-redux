def _pin_header_fp(
    ref: str,
    value: str,
    net_names: tuple[str, ...] | list[str],
    x: float,
    y: float,
    *,
    pitch: float = 2.54,
) -> list:
    """Load official KiCad pin-header footprint and bind nets (DRC-clean)."""
    del pitch
    n = len(net_names)
    mod_name = f"PinHeader_1x{n:02d}_P2.54mm_Vertical"
    lib_id = f"Connector_PinHeader_2.54mm:{mod_name}"
    path = PINHEADER_PRETTY / f"{mod_name}.kicad_mod"
    if not path.is_file():
        raise FileNotFoundError(path)
    tree = parse_sexpr(path.read_text(encoding="utf-8"))
    if not isinstance(tree, list) or tree[0] != "footprint":
        raise ValueError(f"bad footprint file {path}")

    # Clone and rewrite as a board footprint instance.
    fp: list = ["footprint", lib_id]
    skip_heads = {
        "version",
        "generator",
        "generator_version",
        "layer",  # re-added below
        "tedit",
        "uuid",
        "at",
    }
    body_nodes = []
    for node in tree[2:]:
        if isinstance(node, list) and node and node[0] in skip_heads:
            continue
        body_nodes.append(node)

    fp.extend(
        [
            ["layer", "F.Cu"],
            ["uuid", det_uuid(f"fp/{ref}")],
            ["at", x, y],
            [
                "property",
                "Reference",
                ref,
                ["at", 0, -2.5, 0],
                ["layer", "F.SilkS"],
                ["uuid", det_uuid(f"fp/{ref}/prop/Reference")],
            ],
            [
                "property",
                "Value",
                value,
                ["at", 0, 2.5, 0],
                ["layer", "F.Fab"],
                ["uuid", det_uuid(f"fp/{ref}/prop/Value")],
            ],
            [
                "property",
                "Footprint",
                lib_id,
                ["at", 0, 0, 0],
                ["layer", "F.Fab"],
                ["hide", True],
                ["uuid", det_uuid(f"fp/{ref}/prop/Footprint")],
            ],
        ]
    )

    pad_i = 0
    for node in body_nodes:
        if isinstance(node, list) and node and node[0] == "pad":
            pad_i += 1
            net_name = net_names[pad_i - 1]
            new_pad = [x for x in node if not (isinstance(x, list) and x and x[0] in ("uuid", "net"))]
            new_pad.append(["net", pad_i, net_name])  # net id patched later
            new_pad.append(["uuid", det_uuid(f"pad/{ref}/{pad_i}")])
            fp.append(new_pad)
        elif isinstance(node, list) and node and node[0] == "fp_text":
            # Library uses bare reference/value; set instance texts.
            txt = list(node)
            if len(txt) >= 3 and txt[1] == "reference":
                txt[2] = ref
            elif len(txt) >= 3 and txt[1] == "value":
                txt[2] = value
            # restamp tstamp/uuid children if present
            cleaned = []
            for part in txt:
                if isinstance(part, list) and part and part[0] in ("tstamp", "uuid"):
                    continue
                cleaned.append(part)
            kind = cleaned[1] if len(cleaned) > 1 else "x"
            cleaned.append(["uuid", det_uuid(f"fp/{ref}/fp_text/{kind}")])
            fp.append(cleaned)
        elif isinstance(node, list) and node and node[0] == "property":
            prop = list(node)
            pname = prop[1] if len(prop) > 1 else ""
            prop = [p for p in prop if not (isinstance(p, list) and p and p[0] == "uuid")]
            if pname == "Reference":
                prop[2] = ref
            elif pname == "Value":
                prop[2] = value
            elif pname == "Footprint":
                prop[2] = lib_id
            prop.append(["uuid", det_uuid(f"fp/{ref}/prop/{pname}")])
            fp.append(prop)
        else:
            fp.append(node)

    nets = [["net", i + 1, net_names[i]] for i in range(n)]
    return fp, nets



def _emit_pcb(
    out_dir: Path,
    name: str,
    width_mm: float,
    height_mm: float,
    connectors: list[tuple[str, str, tuple[str, ...] | list[str], float, float]],
    bom_fps: list[tuple[str, str, str, float, float]],
) -> Path:
    """Fab-oriented PCB: outline + headers (netted) + BOM footprints (no nets yet)."""
    all_nets: dict[str, int] = {}
    net_list: list = [["net", 0, ""]]
    footprints: list = []
    seen: set[str] = set()

    next_id = 1
    for ref, value, pins, x, y in connectors:
        local_nets = []
        for p in pins:
            if p in seen:
                raise ValueError(
                    f"PCB {name}: net {p!r} repeated on {ref}; "
                    "keep one pad per net for DRC-clean connector boards"
                )
            seen.add(p)
            if p not in all_nets:
                all_nets[p] = next_id
                net_list.append(["net", next_id, p])
                next_id += 1
            local_nets.append(p)
        fp, _ = _pin_header_fp(ref, value, local_nets, x, y)
        for node in fp:
            if isinstance(node, list) and node and node[0] == "pad":
                for i, sub in enumerate(node):
                    if isinstance(sub, list) and sub and sub[0] == "net":
                        nname = sub[2]
                        node[i] = ["net", all_nets[nname], nname]
        footprints.append(fp)

    for ref, value, fp_id, x, y in bom_fps:
        footprints.append(load_board_footprint(fp_id, ref, value, x, y))

    body: list = [
        "kicad_pcb",
        ["version", KICAD_PCB_VERSION],
        ["generator", "core-memory-redux"],
        ["generator_version", "10.0"],
        ["general", ["thickness", 1.6], ["legacy_teardrops", False]],
        ["paper", "A4"],
        _pcb_layers_2(),
        [
            "setup",
            ["pad_to_mask_clearance", 0],
        ],
        *net_list,
        [
            "gr_rect",
            ["start", 0, 0],
            ["end", width_mm, height_mm],
            ["stroke", ["width", 0.1], ["type", "default"]],
            ["fill", "none"],
            ["layer", "Edge.Cuts"],
            ["uuid", det_uuid(f"edge/{name}")],
        ],
        [
            "gr_text",
            name,
            ["at", width_mm / 2, 5],
            ["layer", "F.SilkS"],
            ["uuid", det_uuid(f"silk/{name}")],
            ["effects", ["font", ["size", 2, 2], ["thickness", 0.3]]],
        ],
        *footprints,
    ]
    path = out_dir / f"{name}.kicad_pcb"
    write_sexpr(path, body)
    return path


