    key = "pcb_axis_octal"
    body, suuid = _sheet_base(
        key,
        f"pcb_axis_octal — decode+DMOS+SS14 group g={group} (X/Y identical PCB)",
        8,
        [_lib_diode(), _lib_r(), _lib_stub()],
    )
    lib_cache: dict[str, list] = {}
